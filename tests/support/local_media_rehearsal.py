def expected_visual_count(duration_seconds: Decimal = SYNTHETIC_NARRATION_SECONDS) -> int:
    """Mirror the A3 rule of one visual per six seconds of verified audio."""
    return max(1, math.ceil(duration_seconds / _SECONDS_PER_VISUAL))


def write_synthetic_narration_wav(
    _text: str,
    destination: Path,
    voice_id: str,
    language_code: str,
) -> TTSAdapterResult:
    """Write a deterministic PCM S16LE mono tone in place of real narration."""
    frame_count = int(SYNTHETIC_NARRATION_SECONDS) * SYNTHETIC_SAMPLE_RATE_HZ
    samples = bytearray()
    for index in range(frame_count):
        seconds = index / SYNTHETIC_SAMPLE_RATE_HZ
        frequency = _TONE_BASE_HZ * (1.0 + 0.5 * math.floor(seconds / 3.0))
        value = int(_TONE_AMPLITUDE * math.sin(2.0 * math.pi * frequency * seconds))
        samples += struct.pack("<h", value)
    with wave.open(str(destination), "wb") as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(SYNTHETIC_SAMPLE_RATE_HZ)
        audio.writeframes(bytes(samples))
    return TTSAdapterResult(
        backend=REHEARSAL_TTS_BACKEND,
        model_id="deterministic-tone-v1",
        voice_id=voice_id,
        language_code=language_code,
        license_id=REHEARSAL_LICENSE_ID,
    )


def write_synthetic_visual_import(
    import_root: Path,
    *,
    count: int,
    width: int,
    height: int,
    manifest_name: str = "manifest.json",
) -> Path:
    """Publish synthetic PNGs plus a strict A3 manifest inside one contained root."""
    if count < 1:
        raise ValueError("rehearsal needs at least one visual")
    import_root.mkdir(parents=True, exist_ok=True)
    assets: list[dict[str, object]] = []
    for index in range(1, count + 1):
        file_name = f"rehearsal-{index:03d}.png"
        path = import_root / file_name
        path.write_bytes(_synthetic_png(width=width, height=height, index=index))
        assets.append(
            {
                "relative_path": file_name,
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "source_type": "generated",
                "provider": "automation-foundry",
                "model_id": "synthetic-rehearsal-frame-v1",
                "source_id": f"rehearsal-frame-{index:03d}",
                "source_uri": (
                    "local-model://automation-foundry/synthetic-rehearsal-frame-v1/"
                    f"{index:03d}"
                ),
                "license_id": REHEARSAL_LICENSE_ID,
                "commercial_use": True,
                "attribution": (
                    "Quadro sintético gerado pelo próprio projeto para quality test; "
                    "não é imagem de terceiro nem substitui um pacote visual revisado."
                ),
            }
        )
    manifest_path = import_root / manifest_name
    manifest_path.write_text(
        json.dumps({"schema_version": 1, "assets": assets}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return manifest_path


