"""Synthetic local-media fixtures for the Content Engine A1 to A6 rehearsal.

Every asset produced here is generated by this repository at test time:

- the WAV is a deterministic tone, never Kokoro output and never a human voice;
- the PNGs are flat synthetic frames, never photographs or model output;
- no download, network call, external API or third-party asset is involved.

The fixtures exist to exercise the real A3 import, A4 timing, A5 assembly and A6
originality contracts against each other. They do not validate narration
quality, editorial value, rights over real imagery or caption synchronism with a
real voice. Those still depend on Kokoro on the RTX 3090, a reviewed visual
package and human review, and remain explicitly pending.
"""

