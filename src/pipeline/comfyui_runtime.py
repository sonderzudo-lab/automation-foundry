def model_inventory_sha256(inventory: Mapping[str, str]) -> str:
    """Digest of the pinned weight files, recorded in each manifest and cache key."""
    return hashlib.sha256(
        "\n".join(f"{path}:{digest}" for path, digest in sorted(inventory.items())).encode("utf-8")
    ).hexdigest()


