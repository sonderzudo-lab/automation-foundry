class SceneVideoError(RuntimeError):
    """Base of the renderer failures; ``code`` is safe to persist."""

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


class SceneVideoUnavailableError(SceneVideoError):
    """The runtime could not run now (no RAM, did not start, stopped answering); retry."""


class SceneVideoMisconfiguredError(SceneVideoError):
    """Wrong version, weights or paths; retrying will not help."""


class SceneClipFailedError(SceneVideoError):
    """This clip failed for good (the graph failed on it, bad frames); others may work."""


class SceneClipTimeoutError(SceneVideoError):
    """This clip ran past its timeout; the runtime was stopped and must start again."""


@dataclass(frozen=True, slots=True)
class ClipRenderRequest:
    """One clip: the approved image, its motion, and the exact frames to generate."""

    index: int
    image_path: Path
    image_sha256: str
    motion: str
    seed: int
