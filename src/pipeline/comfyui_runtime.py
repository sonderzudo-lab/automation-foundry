"""Local ComfyUI used as a render tool for the animated scenes (A5a), LTX-2.3 only.

ComfyUI is treated like Remotion or FFmpeg: a pinned local program, started by
the step and stopped at the end of the attempt, never a service left running.
Before it starts, the renderer checks the version of the checkout (v0.40.0), the
SHA-256 of the three weight files the graph loads, the free RAM, and frees the
local text model. Nothing is downloaded: the process runs offline, without
custom nodes, on 127.0.0.1 and a free port, in a workspace of its own whose only
model folder is the checked one.

The graph is built here, in code, and is the one of the lab
(``D:\\automation-foundry\\labs\\video-wan22-i2v\\render_ltx.py``, official
template ``video_ltx2_3_i2v``): 8 distilled steps at half resolution, a 2x
latent upscale, 3 refinement steps; the audio branch is generated by the model
and discarded. ComfyUI saves PNG frames and FFmpeg (pinned) encodes the clip.

A clip that takes longer than its timeout, or a server that stops answering,
has the whole process tree killed, as A5 already does with Remotion.

Everything the step needs goes through ``SceneVideoRenderer``, so tests run with
a fake.
"""

