class ComfyUILtx23Renderer:
    """Starts the pinned ComfyUI in ``workspace`` and renders LTX-2.3 clips through it."""

    def __init__(
        self,
        config: ComfyUIConfig,
        *,
        workspace: Path,
        release_text_model: Callable[[], None] | None = None,
        encoder: ClipEncoder | None = None,
        available_ram_bytes: Callable[[], int] | None = None,
        sample_memory: MemorySampler | None = None,
    ) -> None:
        self._config = config
        self._workspace = workspace
        self._release_text_model = release_text_model
        self._encoder = encoder
        self._available_ram_bytes = available_ram_bytes or _available_ram_bytes
        self._sample_memory = sample_memory or _sample_memory
        self._inventory_sha256 = model_inventory_sha256(config.inventory)
        self._process: subprocess.Popen[bytes] | None = None
        self._log_handle: IO[bytes] | None = None
        self._port: int | None = None
        self._comfyui: Path | None = None
        self._python: Path | None = None
        self._job: _KillOnCloseJob | None = None
        # Descendants seen while ComfyUI ran (pid -> creation time). A process the
        # job cannot hold (a Microsoft Store Python breaks away) is still killed.
        self._descendants: dict[int, float] = {}
        self._watch_stop: threading.Event | None = None
        self._watcher: threading.Thread | None = None
        self._released = False
        # close() may run while start() is still checking in another thread (the
        # step's attempt timed out): the lock and the flag stop that start from
        # launching anything afterwards.
        self._lock = threading.RLock()
        self._closed = False

    @property
    def provider(self) -> str:
        return LTX23_PROVIDER

    @property
    def model_id(self) -> str:
        return (
            f"{LTX23_MODEL_REPOSITORY}@{LTX23_MODEL_REVISION}"
            f"#inventory-sha256:{self._inventory_sha256[:16]}"
        )

    @property
    def graph_version(self) -> str:
        return LTX23_GRAPH_VERSION

    @property
    def license_id(self) -> str:
        return LTX23_LICENSE_ID

    @property
    def inventory_sha256(self) -> str:
        return self._inventory_sha256

    @property
    def running(self) -> bool:
        return self._process is not None and self._process.poll() is None

    @property
    def log_path(self) -> Path:
        return self._workspace / "comfyui.log"

    def start(self, *, timeout_seconds: float) -> None:
        """Check everything, then start ComfyUI and wait until it answers.

        The weights are checked before every start, also after a clip timeout;
        the install, FFmpeg and the release of the text model only once.
        """
        if self.running:
            return
        self._stop_process()
        self._ensure_open()
        deadline = time.monotonic() + timeout_seconds
        if self._comfyui is None or self._python is None:
            comfyui, python = self._verified_install()
            if self._encoder is None:
                self._encoder = ffmpeg_clip_encoder(
                    _verified_ffmpeg(self._config.ffmpeg_path, self._config.ffmpeg_sha256)
                )
            self._comfyui, self._python = comfyui, python
        models = self._verified_models()
        self._ensure_open()
        self._write_workspace(models)
        if self._release_text_model is not None and not self._released:
            # Best effort, as in A3 and A5: a failure shows up as a lack of memory.
            try:
                self._release_text_model()
            except Exception:
                log.warning("scene_animation_text_model_release_failed")
            self._released = True
        available = self._available_ram_bytes()
        if available < self._config.min_free_ram_bytes:
            log.warning(
                "scene_animation_ram_insufficient",
                available_gb=round(available / 1024**3, 1),
                required_gb=round(self._config.min_free_ram_bytes / 1024**3, 1),
            )
            raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_RAM_INSUFFICIENT")
        self._launch(deadline)

    def render(self, request: ClipRenderRequest, *, timeout_seconds: float) -> ClipRenderResult:
        """Render one clip into ``request.output_path``; the runtime must be running."""
        if not self.running or self._port is None:
            raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_NOT_RUNNING")
        if self._encoder is None:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_ENCODER_MISSING")
        if request.format not in LTX23_GENERATION_SIZE:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_FORMAT_INVALID")
        started = time.monotonic()
        deadline = started + timeout_seconds
        image_name = f"scene-{request.index:03d}-{uuid4().hex[:8]}.png"
        image_copy = self._workspace / "input" / image_name
        shutil.copyfile(request.image_path, image_copy)
        if _sha256_file(image_copy) != request.image_sha256:
            raise SceneClipFailedError("CONTENT_SCENE_ANIMATION_IMAGE_HASH_MISMATCH")
        frames_folder = f"clip-{request.index:03d}-{uuid4().hex[:8]}"
        width, height = LTX23_GENERATION_SIZE[request.format]
        graph = ltx23_graph(
            image_name=image_name,
            motion=request.motion,
            seed=request.seed,
            frames=request.frames,
            width=width,
            height=height,
            filename_prefix=f"{frames_folder}/{_FRAME_PREFIX}",
        )
        sampler = _PeakSampler(self._sample_memory)
        sampler.start()
        try:
            status = self._run_prompt(graph, deadline)
        finally:
            sampler.stop()
        if status.get("status_str") != "success" or status.get("completed") is not True:
            log.warning(
                "scene_animation_clip_failed",
                index=request.index,
                detail=_execution_error(status)[:_LOG_TAIL_CHARS],
            )
            raise SceneClipFailedError("CONTENT_SCENE_ANIMATION_CLIP_FAILED")
        frames_dir = self._workspace / "output" / frames_folder
        frames = sorted(frames_dir.glob(f"{_FRAME_PREFIX}_*_.png"))
        if len(frames) != request.frames:
            raise SceneClipFailedError("CONTENT_SCENE_ANIMATION_FRAMES_INVALID")
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise SceneClipTimeoutError("CONTENT_SCENE_ANIMATION_CLIP_TIMEOUT")
        try:
            self._encoder(
                frames,
                request.output_path,
                request.width,
                request.height,
                min(remaining, _ENCODE_TIMEOUT_SECONDS),
            )
        except subprocess.TimeoutExpired as exc:
            raise SceneClipTimeoutError("CONTENT_SCENE_ANIMATION_CLIP_TIMEOUT") from exc
        except (OSError, subprocess.SubprocessError) as exc:
            raise SceneClipFailedError("CONTENT_SCENE_ANIMATION_ENCODE_FAILED") from exc
        finally:
            shutil.rmtree(frames_dir, ignore_errors=True)
            image_copy.unlink(missing_ok=True)
        return ClipRenderResult(
            seconds=time.monotonic() - started,
            peak_vram_mib=sampler.peak_vram_mib,
            peak_ram_bytes=sampler.peak_ram_bytes,
        )

    def close(self) -> None:
        """Stop the whole process tree for good; a start still checking will not launch."""
        with self._lock:
            self._closed = True
            self._stop_process()

    def _ensure_open(self) -> None:
        if self._closed:
            raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_RUNTIME_CLOSED")

    def _stop_process(self) -> None:
        """Kill ComfyUI and every process it started, even after ComfyUI itself exited."""
        with self._lock:
            process, self._process, self._port = self._process, None, None
            job, self._job = self._job, None
            watch_stop, watcher = self._watch_stop, self._watcher
            self._watch_stop, self._watcher = None, None
            if watch_stop is not None and watcher is not None:
                watch_stop.set()
                watcher.join(timeout=5)
            if process is not None:
                self._track_descendants(process)
            if job is not None:
                job.terminate()
            if process is not None:
                if job is None or process.poll() is None:
                    _kill_process_tree(process)
                with contextlib.suppress(subprocess.TimeoutExpired):
                    process.wait(timeout=30)
            descendants, self._descendants = self._descendants, {}
            _kill_known_processes(descendants)
            if self._log_handle is not None:
                self._log_handle.close()
                self._log_handle = None

    def _verified_install(self) -> tuple[Path, Path]:
        try:
            comfyui = Path(self._config.comfyui_dir).resolve(strict=True)
            python = Path(self._config.python_path).resolve(strict=True)
            version_text = (comfyui / "comfyui_version.py").read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise SceneVideoMisconfiguredError(
                "CONTENT_SCENE_ANIMATION_COMFYUI_UNAVAILABLE"
            ) from exc
        if not (comfyui / "main.py").is_file() or not python.is_file():
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_COMFYUI_UNAVAILABLE")
        if f'__version__ = "{COMFYUI_VERSION}"' not in version_text:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_COMFYUI_VERSION_MISMATCH")
        if self._config.sage_attention and not _has_sage_attention(python):
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_SAGE_ATTENTION_UNAVAILABLE")
        return comfyui, python

    def _verified_models(self) -> Path:
        folder = self._config.models_dir or str(Path(self._config.comfyui_dir) / "models")
        try:
            models = Path(folder).resolve(strict=True)
        except OSError as exc:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_MODEL_UNAVAILABLE") from exc
        for relative, expected in sorted(self._config.inventory.items()):
            self._ensure_open()
            path = models / relative
            if path.is_symlink() or not path.is_file():
                raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_MODEL_UNAVAILABLE")
            if _sha256_unchanged_file(path) != expected:
                raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_MODEL_HASH_MISMATCH")
        return models

    def _write_workspace(self, models: Path) -> None:
        for name in ("input", "output", "temp", "user", "models", "custom_nodes"):
            (self._workspace / name).mkdir(parents=True, exist_ok=True)
        folders = sorted({Path(relative).parts[0] for relative in self._config.inventory})
        # The checked folder is the only place ComfyUI looks for weights.
        lines = ["automation_foundry:", f"  base_path: {json.dumps(models.as_posix())}"]
        lines += [f"  {name}: {name}" for name in folders]
        (self._workspace / "extra_model_paths.yaml").write_text(
            "\n".join(lines) + "\n", encoding="utf-8"
        )

    def _launch(self, deadline: float) -> None:
        if self._comfyui is None or self._python is None:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_COMFYUI_UNAVAILABLE")
        port = _free_port()
        arguments = [
            str(self._python),
            "main.py",
            "--listen",
            _HOST,
            "--port",
            str(port),
            "--base-directory",
            str(self._workspace),
            "--extra-model-paths-config",
            str(self._workspace / "extra_model_paths.yaml"),
            "--disable-auto-launch",
            "--disable-all-custom-nodes",
            "--offline",
        ]
        if self._config.sage_attention:
            arguments.append("--use-sage-attention")
        if self._config.fp16_accumulation:
            arguments += ["--fast", "fp16_accumulation"]
        with self._lock:
            self._ensure_open()
            if time.monotonic() >= deadline:
                # The checks took the whole start budget: launching now would overrun it.
                raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_START_TIMEOUT")
            self._log_handle = self.log_path.open("ab")
            try:
                process = subprocess.Popen(
                    arguments,
                    cwd=self._comfyui,
                    stdin=subprocess.DEVNULL,
                    stdout=self._log_handle,
                    stderr=subprocess.STDOUT,
                    shell=False,
                    start_new_session=sys.platform != "win32",
                    # Suspended until it is in the job: the venv's python.exe starts
                    # the real interpreter at once, which must not escape the job.
                    creationflags=_CREATE_SUSPENDED if sys.platform == "win32" else 0,
                    env={
                        **os.environ,
                        "HF_HUB_OFFLINE": "1",
                        "TRANSFORMERS_OFFLINE": "1",
                        "PYTHONNOUSERSITE": "1",
                    },
                )
            except OSError as exc:
                self._stop_process()
                raise SceneVideoUnavailableError(
                    "CONTENT_SCENE_ANIMATION_COMFYUI_START_FAILED"
                ) from exc
            self._process = process
            self._job = _attach_kill_on_close_job(process)
            self._watch_stop = threading.Event()
            self._watcher = threading.Thread(
                target=self._watch_descendants, args=(process, self._watch_stop), daemon=True
            )
            self._watcher.start()
            if sys.platform == "win32" and not _resume_process(process.pid):
                self._stop_process()
                raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_START_FAILED")
            self._port = port
        while True:
            if process.poll() is not None:
                self._log_tail("scene_animation_comfyui_exited")
                self._stop_process()
                raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_EXITED")
            try:
                stats = self._call("GET", "/system_stats")
            except (OSError, ValueError):
                stats = None
            if stats is not None:
                system = stats.get("system")
                version = system.get("comfyui_version") if isinstance(system, dict) else None
                if version != COMFYUI_VERSION:
                    # Another program answered on this port, or the checkout changed.
                    self._stop_process()
                    raise SceneVideoMisconfiguredError(
                        "CONTENT_SCENE_ANIMATION_COMFYUI_VERSION_MISMATCH"
                    )
                log.info("scene_animation_comfyui_started", port=port)
                return
            if time.monotonic() >= deadline:
                self._log_tail("scene_animation_comfyui_start_timeout")
                self._stop_process()
                raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_START_TIMEOUT")
            time.sleep(min(self._config.poll_interval_seconds, 1.0))

    def _run_prompt(self, graph: dict[str, dict[str, Any]], deadline: float) -> dict[str, Any]:
        try:
            queued = self._call("POST", "/prompt", {"prompt": graph, "client_id": uuid4().hex})
        except urllib.error.HTTPError as exc:
            # ComfyUI refuses a graph it cannot run (unknown node, missing file).
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_GRAPH_REFUSED") from exc
        except (OSError, ValueError) as exc:
            self._stop_process()
            raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_UNREACHABLE") from exc
        prompt_id = queued.get("prompt_id")
        if not isinstance(prompt_id, str) or not prompt_id:
            raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_GRAPH_REFUSED")
        while True:
            if not self.running:
                self._log_tail("scene_animation_comfyui_exited")
                self._stop_process()
                raise SceneVideoUnavailableError("CONTENT_SCENE_ANIMATION_COMFYUI_EXITED")
            try:
                history = self._call("GET", f"/history/{prompt_id}")
            except (OSError, ValueError):
                history = {}
            entry = history.get(prompt_id)
            if isinstance(entry, dict):
                status = entry.get("status")
                return status if isinstance(status, dict) else {}
            if time.monotonic() >= deadline:
                # The clip is abandoned with the whole tree; the next one starts again.
                self._stop_process()
                raise SceneClipTimeoutError("CONTENT_SCENE_ANIMATION_CLIP_TIMEOUT")
            time.sleep(self._config.poll_interval_seconds)

    def _call(
        self, method: str, path: str, payload: dict[str, Any] | None = None
    ) -> dict[str, Any]:
        if self._port is None:
            raise OSError("ComfyUI is not running")
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        request = urllib.request.Request(
            f"http://{_HOST}:{self._port}{path}",
            data=data,
            method=method,
            headers={"Content-Type": "application/json"},
        )
        # Loopback only: never through a proxy from the environment.
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(request, timeout=_HTTP_TIMEOUT_SECONDS) as response:
            decoded = json.loads(response.read().decode("utf-8"))
        if not isinstance(decoded, dict):
            raise ValueError("ComfyUI answered something other than an object")
        return decoded

    def _watch_descendants(self, process: subprocess.Popen[bytes], stop: threading.Event) -> None:
        # HTTP calls may block for seconds; this keeps seeing short-lived helpers.
        while not stop.wait(_WATCH_INTERVAL_SECONDS):
            self._track_descendants(process)

    def _track_descendants(self, process: subprocess.Popen[bytes]) -> None:
        try:
            children = psutil.Process(process.pid).children(recursive=True)
        except psutil.Error:
            return
        for child in children:
            with contextlib.suppress(psutil.Error):
                self._descendants.setdefault(child.pid, child.create_time())

    def _log_tail(self, event: str) -> None:
        with contextlib.suppress(OSError):
            if self._log_handle is not None:
                self._log_handle.flush()
            text = self.log_path.read_bytes()[-_LOG_TAIL_CHARS:].decode("utf-8", "replace")
            log.warning(event, log_tail=text)


def ffmpeg_clip_encoder(ffmpeg: Path) -> ClipEncoder:
    """Encode the PNG frames as an H.264 clip of the format size, without audio."""

    def encode(frames: list[Path], output: Path, width: int, height: int, timeout: float) -> None:
        if not frames:
            raise OSError("no frames to encode")
        pattern = frames[0].parent / f"{_FRAME_PREFIX}_%05d_.png"
        temporary = output.with_name(f".{output.name}.{uuid4().hex}.tmp.mp4")
        arguments = [
            str(ffmpeg),
            "-hide_banner",
            "-loglevel",
            "error",
            "-nostdin",
            "-y",
            "-framerate",
            str(LTX23_FPS),
            "-start_number",
            "1",
            "-i",
            str(pattern),
            "-frames:v",
            str(len(frames)),
            "-vf",
            (
                f"scale={width}:{height}:force_original_aspect_ratio=increase:flags=lanczos,"
                f"crop={width}:{height},setsar=1"
            ),
            "-c:v",
            "libx264",
            "-crf",
            "16",
            "-pix_fmt",
            "yuv420p",
            "-an",
            "-movflags",
            "+faststart",
            str(temporary),
        ]
        try:
            completed = run_process_tree(arguments, cwd=frames[0].parent, timeout_seconds=timeout)
            if completed.returncode != 0:
                log.warning(
                    "scene_animation_encode_failed",
                    returncode=completed.returncode,
                    stderr_tail=(completed.stderr or "")[-_LOG_TAIL_CHARS:],
                )
                raise OSError("ffmpeg failed")
            os.replace(temporary, output)
        finally:
            temporary.unlink(missing_ok=True)

    return encode


def run_process_tree(
    arguments: list[str],
    *,
    cwd: Path,
    timeout_seconds: float,
) -> subprocess.CompletedProcess[str]:
    """Run without a shell; on timeout stop the whole tree and re-raise."""
    process = subprocess.Popen(
        arguments,
        cwd=cwd,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        shell=False,
        start_new_session=sys.platform != "win32",
    )
    try:
        stdout, stderr = process.communicate(timeout=timeout_seconds)
    except subprocess.TimeoutExpired:
        _kill_process_tree(process)
        with contextlib.suppress(subprocess.TimeoutExpired):
            process.communicate(timeout=30)
        raise
    return subprocess.CompletedProcess(arguments, process.returncode, stdout, stderr)


def _kill_process_tree(process: subprocess.Popen[Any]) -> None:
    """Kill the program and every descendant (ComfyUI may start helpers)."""
    if sys.platform == "win32":
        taskkill = Path(os.environ.get("SYSTEMROOT", "C:/Windows")) / "System32" / "taskkill.exe"
        with contextlib.suppress(OSError, subprocess.TimeoutExpired):
            subprocess.run(
                [str(taskkill), "/PID", str(process.pid), "/T", "/F"],
                stdin=subprocess.DEVNULL,
                capture_output=True,
                timeout=30,
                check=False,
                shell=False,
            )
    else:
        with contextlib.suppress(OSError):
            os.killpg(process.pid, signal.SIGKILL)
    with contextlib.suppress(OSError):
        process.kill()


class _KillOnCloseJob:
    """A Windows job holding ComfyUI and every process it starts.

    Terminating the job kills them all, even when ComfyUI itself already exited
    and ``taskkill /T`` could no longer find its descendants.
    """

    def __init__(self, pid: int) -> None:
        if sys.platform != "win32":
            raise OSError("job objects exist only on Windows")
        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        _configure_kernel32(kernel32)
        kernel32.OpenProcess.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32]
        kernel32.OpenProcess.restype = ctypes.c_void_p
        kernel32.TerminateJobObject.argtypes = [ctypes.c_void_p, ctypes.c_uint]
        kernel32.TerminateJobObject.restype = ctypes.c_int
        job = kernel32.CreateJobObjectW(None, None)
        if not job:
            raise ctypes.WinError(ctypes.get_last_error())
        information = _job_limit_information()
        process = None
        try:
            if not kernel32.SetInformationJobObject(
                job, 9, ctypes.byref(information), ctypes.sizeof(information)
            ):
                raise ctypes.WinError(ctypes.get_last_error())
            process = kernel32.OpenProcess(_PROCESS_SET_QUOTA | _PROCESS_TERMINATE, 0, pid)
            if not process or not kernel32.AssignProcessToJobObject(job, process):
                raise ctypes.WinError(ctypes.get_last_error())
        except OSError:
            kernel32.CloseHandle(job)
            raise
        finally:
            if process:
                kernel32.CloseHandle(process)
        self._kernel32 = kernel32
        self._job = job

    def terminate(self) -> None:
        if self._job:
            self._kernel32.TerminateJobObject(self._job, 1)
            self._kernel32.CloseHandle(self._job)
            self._job = None


def _kill_known_processes(known: Mapping[int, float]) -> None:
    """Kill each process still alive under the same pid and creation time."""
    for pid, created in known.items():
        with contextlib.suppress(psutil.Error):
            process = psutil.Process(pid)
            if process.create_time() == created:
                process.kill()


def _resume_process(pid: int) -> bool:
    """Resume a process created suspended (all of its threads)."""
    if sys.platform != "win32":
        return True
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.OpenProcess.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32]
    kernel32.OpenProcess.restype = ctypes.c_void_p
    kernel32.CloseHandle.argtypes = [ctypes.c_void_p]
    ntdll = ctypes.WinDLL("ntdll")
    ntdll.NtResumeProcess.argtypes = [ctypes.c_void_p]
    ntdll.NtResumeProcess.restype = ctypes.c_long
    handle = kernel32.OpenProcess(_PROCESS_SUSPEND_RESUME, 0, pid)
    if not handle:
        return False
    try:
        return bool(ntdll.NtResumeProcess(handle) == 0)
    finally:
        kernel32.CloseHandle(handle)


def _attach_kill_on_close_job(process: subprocess.Popen[Any]) -> _KillOnCloseJob | None:
    if sys.platform != "win32":
        return None
    try:
        return _KillOnCloseJob(process.pid)
    except OSError:
        # Still stopped through taskkill /T, which needs ComfyUI to be alive.
        log.warning("scene_animation_job_object_unavailable")
        return None


class _PeakSampler:
    """Peak VRAM and system RAM while one clip renders, sampled once a second."""

    def __init__(self, sample: MemorySampler) -> None:
        self._sample = sample
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self.peak_vram_mib: int | None = None
        self.peak_ram_bytes: int | None = None

    def start(self) -> None:
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()
        self._thread.join(timeout=10)

    def _loop(self) -> None:
        while True:
            try:
                vram, ram = self._sample()
            except Exception:
                vram, ram = None, 0
            if vram is not None:
                self.peak_vram_mib = max(self.peak_vram_mib or 0, vram)
            if ram:
                self.peak_ram_bytes = max(self.peak_ram_bytes or 0, ram)
            if self._stop.wait(1.0):
                return


def _sample_memory() -> tuple[int | None, int]:
    vram: int | None = None
    smi = shutil.which("nvidia-smi")
    if smi is not None:
        with contextlib.suppress(OSError, subprocess.SubprocessError):
            out = (
                subprocess.run(
                    [smi, "--query-gpu=memory.used", "--format=csv,noheader,nounits"],
                    stdin=subprocess.DEVNULL,
                    capture_output=True,
                    text=True,
                    timeout=5,
                    check=False,
                    shell=False,
                )
                .stdout.strip()
                .splitlines()
            )
            if out and out[0].strip().isdigit():
                vram = int(out[0].strip())
    return vram, int(psutil.virtual_memory().used)


def _available_ram_bytes() -> int:
    return int(psutil.virtual_memory().available)


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind((_HOST, 0))
        return int(probe.getsockname()[1])


def _has_sage_attention(python: Path) -> bool:
    environment = python.parent.parent
    patterns = (
        "Lib/site-packages/sageattention-2.2.0*.dist-info",
        "lib/python3*/site-packages/sageattention-2.2.0*.dist-info",
    )
    return any(any(environment.glob(pattern)) for pattern in patterns)


def _verified_ffmpeg(configured: str, expected_sha256: str | None) -> Path:
    discovered = shutil.which(configured.strip()) if configured.strip() else None
    try:
        ffmpeg = Path(discovered or configured).resolve(strict=True)
    except OSError as exc:
        raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_FFMPEG_UNAVAILABLE") from exc
    if not ffmpeg.is_file():
        raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_FFMPEG_UNAVAILABLE")
    if (
        expected_sha256 is not None
        and _sha256_unchanged_file(ffmpeg) != expected_sha256.strip().lower()
    ):
        raise SceneVideoMisconfiguredError("CONTENT_SCENE_ANIMATION_FFMPEG_HASH_MISMATCH")
    return ffmpeg


def _execution_error(status: Mapping[str, Any]) -> str:
    messages = status.get("messages")
    if isinstance(messages, list):
        for message in messages:
            if (
                isinstance(message, list)
                and len(message) == 2
                and message[0] == "execution_error"
                and isinstance(message[1], dict)
            ):
                return str(message[1].get("exception_message", "execution error"))
    return str(status.get("status_str", "unknown"))


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(8 * 1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _sha256_unchanged_file(path: Path) -> str:
    """Hash a multi-gigabyte weight file once per identity, size and timestamps.

    A file replaced by another one gets a new file id and creation time, so it is
    read again even when size and modification time were made to match.
    """
    stat = path.stat()
    return _sha256_file_cached(
        str(path), stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns
    )


@lru_cache(maxsize=16)
def _sha256_file_cached(path: str, _inode: int, _size: int, _mtime_ns: int, _ctime_ns: int) -> str:
    return _sha256_file(Path(path))
