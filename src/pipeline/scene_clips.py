"""Contract of the animated scenes of one video (step A5a), read by the montage (A5).

Each approved A3 image becomes either a short video clip generated by the video
model, or stays a still image with the zoom of the montage, with the reason
recorded. The manifest fixes, per scene, the span it covers (the cuts computed
by ``timeline_builder.scene_spans`` from the A4 words), the motion phrase and
seed used, and the clip file with its SHA-256. A5 recomputes the cuts and
refuses a manifest made for other cuts.

Clip length is decided here, not by any model. A clip covers its span plus half
of each crossfade around it, is generated at ``SCENE_CLIP_FPS`` with a number of
frames of the form 8k+1 (what LTX-2.3 accepts) and never exceeds
``MAX_SCENE_CLIP_FRAMES``: in the lab a 9 s clip took 63.7 GB of a 64 GB machine.
A longer scene is played up to ``MAX_SCENE_CLIP_STRETCH`` slower; beyond that it
stays a still image (``too_long``).
"""

from __future__ import annotations

import math
from fractions import Fraction
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from src.pipeline.scene_motion import NEUTRAL_MOTION, motion_problem
from src.pipeline.timeline import (
    FORMAT_DIMENSIONS,
    MAX_TIMELINE_CLIPS,
    MAX_TIMELINE_MS,
    MAX_TRANSITION_MS,
    MAX_VIDEO_STRETCH,
    MIN_CLIP_MS,
    VideoFormat,
    clip_window,
)
from src.pipeline.timeline_builder import SceneSpan, scene_cuts_sha256

SCENE_CLIPS_SCHEMA_VERSION = 1
SCENE_CLIP_FPS = 25
SCENE_CLIP_FRAME_STEP = 8
MIN_SCENE_CLIP_FRAMES = 9
MAX_SCENE_CLIP_FRAMES = 201  # 8.04 s at 25 fps
MAX_SCENE_CLIP_STRETCH = MAX_VIDEO_STRETCH
# Why a scene kept its still image.
StillReason = Literal["too_long", "generation_failed", "owner_choice"]

_SHA256 = r"^[0-9a-f]{64}$"
_IMAGE_NAME = r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}\.png$"
_VIDEO_NAME = r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}\.mp4$"


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class _Scene(_Strict):
    index: int = Field(ge=1, le=MAX_TIMELINE_CLIPS)
    image: str = Field(pattern=_IMAGE_NAME)
    image_sha256: str = Field(pattern=_SHA256)
    start_ms: int = Field(ge=0, le=MAX_TIMELINE_MS)
    end_ms: int = Field(ge=1, le=MAX_TIMELINE_MS)


class AnimatedScene(_Scene):
    """A scene played as the clip generated from its image."""

    kind: Literal["clip"]
    motion: str = Field(min_length=1, max_length=300)
    seed: int = Field(ge=0, le=2**63 - 1)
    frames: int = Field(ge=MIN_SCENE_CLIP_FRAMES, le=MAX_SCENE_CLIP_FRAMES)
    video: str = Field(pattern=_VIDEO_NAME)
    video_sha256: str = Field(pattern=_SHA256)


class StillScene(_Scene):
    """A scene that keeps its still image, and why."""

    kind: Literal["still"]
    reason: StillReason


SceneEntry = Annotated[AnimatedScene | StillScene, Field(discriminator="kind")]


class SceneClipsManifest(_Strict):
    """Every scene of one video, animated or still, for the cuts in ``cuts_sha256``."""

    schema_version: Literal[1]
    format: VideoFormat
    width: int
    height: int
    duration_ms: int = Field(ge=MIN_CLIP_MS, le=MAX_TIMELINE_MS)
    # The crossfade of the montage; each clip covers half of it on both sides.
    transition_ms: int = Field(ge=0, le=MAX_TRANSITION_MS)
    fps: Literal[25]
    cuts_sha256: str = Field(pattern=_SHA256)
    provider: str = Field(min_length=1, max_length=64)
    model_id: str = Field(min_length=1, max_length=200)
    # SHA-256 over the inventory of the model files checked before generating.
    model_inventory_sha256: str = Field(pattern=_SHA256)
    graph_version: str = Field(min_length=1, max_length=64)
    license_id: str = Field(min_length=1, max_length=200)
    # Inherited from the A3 images: a clip is never more usable than its source.
    usage_scope: Literal["quality-test-only"] | None
    scenes: list[SceneEntry] = Field(min_length=1, max_length=MAX_TIMELINE_CLIPS)

    @model_validator(mode="after")
    def _check_manifest(self) -> SceneClipsManifest:
        problem = scene_clips_problem(self)
        if problem is not None:
            raise ValueError(problem)
        return self


def scene_clip_window(
    span: SceneSpan | AnimatedScene | StillScene,
    *,
    duration_ms: int,
    transition_ms: int,
) -> tuple[int, int]:
    """The interval a scene's clip must cover: its span and half of each crossfade."""
    return clip_window(
        span.start_ms, span.end_ms, duration_ms=duration_ms, transition_ms=transition_ms
    )


def scene_clip_frames(window_ms: int) -> int | None:
    """Frames to generate for a window, or None when the scene stays a still image.

    The smallest 8k+1 count that covers the window; when that exceeds the
    maximum, the maximum played up to ``MAX_SCENE_CLIP_STRETCH`` slower.
    """
    if window_ms < 1:
        raise ValueError("window_ms must be positive")
    needed = math.ceil(Fraction(window_ms * SCENE_CLIP_FPS, 1000))
    frames = max(
        MIN_SCENE_CLIP_FRAMES,
        math.ceil(Fraction(needed - 1, SCENE_CLIP_FRAME_STEP)) * SCENE_CLIP_FRAME_STEP + 1,
    )
    if frames <= MAX_SCENE_CLIP_FRAMES:
        return frames
    longest_ms = scene_clip_ms(MAX_SCENE_CLIP_FRAMES) * MAX_SCENE_CLIP_STRETCH
    return MAX_SCENE_CLIP_FRAMES if window_ms <= longest_ms else None


def scene_clip_ms(frames: int) -> int:
    """Length of a clip of ``frames`` frames at ``SCENE_CLIP_FPS``."""
    return frames * 1000 // SCENE_CLIP_FPS


def scene_clips_problem(manifest: SceneClipsManifest) -> str | None:
    """Return why a manifest cannot be assembled, or None when it is consistent."""
    if (manifest.width, manifest.height) != FORMAT_DIMENSIONS[manifest.format]:
        return "dimensions do not match the format"
    scenes = manifest.scenes
    if [scene.index for scene in scenes] != list(range(1, len(scenes) + 1)):
        return "scenes are not numbered 1, 2, 3 and so on in order"
    if scenes[0].start_ms != 0:
        return "the first scene does not start at zero"
    if scenes[-1].end_ms != manifest.duration_ms:
        return "the last scene does not end with the audio"
    for previous, scene in zip([None, *scenes[:-1]], scenes, strict=True):
        if scene.end_ms - scene.start_ms < MIN_CLIP_MS:
            return f"scene {scene.index} is shorter than {MIN_CLIP_MS} ms"
        if previous is not None and scene.start_ms != previous.end_ms:
            return f"scene {scene.index} does not start where scene {previous.index} ends"
    spans = [SceneSpan(index=s.index, start_ms=s.start_ms, end_ms=s.end_ms) for s in scenes]
    if scene_cuts_sha256(spans) != manifest.cuts_sha256:
        return "the scenes do not match cuts_sha256"
    videos: set[str] = set()
    for scene in scenes:
        start, end = scene_clip_window(
            scene, duration_ms=manifest.duration_ms, transition_ms=manifest.transition_ms
        )
        frames = scene_clip_frames(end - start)
        if isinstance(scene, StillScene):
            if scene.reason == "too_long" and frames is not None:
                return f"scene {scene.index} is marked too long but fits in a clip"
            continue
        if frames is None:
            return f"scene {scene.index} is too long for a clip"
        if scene.frames != frames:
            return f"scene {scene.index} must have {frames} frames, not {scene.frames}"
        if scene.motion != NEUTRAL_MOTION and motion_problem(scene.motion) is not None:
            return f"scene {scene.index} has a motion that would be refused"
        if scene.video in videos:
            return f"scene {scene.index} reuses the video of another scene"
        videos.add(scene.video)
    return None
